export function getItem(id) {
  return MENU_ITEMS.find((i) => i.id === id) ?? null;
}

// Единый калькулятор цены/КБЖУ (как packages/shared/utils/price-calculator.ts)
export function calculateItemTotals(item, activeLayerIds) {
  const active = new Set(activeLayerIds);
  let price = item.basePrice;
  let grams = 0;
  let kcal = item.baseCalories;
  let protein = 0,
    fat = 0,
    carbs = 0;
  for (const layer of item.layers) {
    if (!active.has(layer.id)) continue;
    price += layer.priceModifier;
    grams += layer.grams;
    kcal += layer.kcal;
    protein += layer.protein;
    fat += layer.fat;
    carbs += layer.carbs;
  }
  const r1 = (n) => Math.round(n * 10) / 10;
  return { price, grams, kcal, protein: r1(protein), fat: r1(fat), carbs: r1(carbs) };
}

export function defaultActiveLayers(item) {
  return item.layers.filter((l) => l.isBase).map((l) => l.id);
}

